import {test,expect} from '@playwright/test';

test('connection token remains active when moving from chat to schedules',async({page})=>{
  await page.route('**/api/**',route=>route.request().headers().authorization==='Bearer fixture-ui-token'?route.continue():route.fulfill({status:401,contentType:'application/json',body:JSON.stringify({detail:'需要 Bearer token'})}));
  await page.goto('/chat');
  await expect(page.getByRole('heading',{name:'连接本地服务'})).toBeVisible();
  await page.getByLabel('管理 Token',{exact:true}).fill('fixture-ui-token');
  await page.getByRole('button',{name:'连接',exact:true}).click();
  await expect(page.getByRole('button',{name:'与 Admin Agent 新建对话',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'定时任务',exact:true}).click();
  await page.getByRole('button',{name:'新建计划',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'计划 Agent'}).locator('option')).toHaveCount(2);
  await expect(page.locator('.connection-modal')).toHaveCount(0);
  await expect(page.locator('.error-banner')).toHaveCount(0);
});

test('Agent list is the only create entry and history has an independent agent filter',async({page})=>{
  await page.goto('/chat');
  await expect(page.getByRole('heading',{name:'选择一个 Agent，开始新对话'})).toBeVisible();
  await expect(page.getByRole('button',{name:'新建对话',exact:true})).toHaveCount(0);
  await expect(page.getByRole('textbox',{name:'消息',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'与 Admin Agent 新建对话',exact:true}).click();
  await page.getByRole('textbox',{name:'消息',exact:true}).fill('筛选测试管理对话');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  await expect(page.locator('.markdown').last()).toContainText('fixture completed');
  const adminHash=new URL(page.url()).hash;
  await page.getByRole('button',{name:'与 finance-agent 新建对话',exact:true}).click();
  await page.getByRole('textbox',{name:'消息',exact:true}).fill('筛选测试财务对话');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  await expect(page.locator('.markdown').last()).toContainText('fixture completed');
  expect(new URL(page.url()).hash).not.toBe(adminHash);
  await expect(page.locator('.history-list')).toContainText('筛选测试管理对话');
  await expect(page.locator('.history-list')).toContainText('筛选测试财务对话');
  await page.getByRole('combobox',{name:'按 Agent 筛选对话'}).selectOption({label:'Admin Agent'});
  await expect(page.locator('.history-list')).toContainText('筛选测试管理对话');
  await expect(page.locator('.history-list')).not.toContainText('筛选测试财务对话');
  await expect(page.locator('.user-message')).toContainText('筛选测试财务对话');
  await page.getByRole('combobox',{name:'按 Agent 筛选对话'}).selectOption('all');
  await expect(page.locator('.history-list')).toContainText('筛选测试财务对话');
  await page.getByRole('button',{name:'与 finance-agent 新建对话',exact:true}).click();
  await expect(page.locator('.user-message')).toHaveCount(0);
});

test('graphical once schedule persists, pauses and produces an entrypoint report',async({page,request})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/chat');
  await page.getByRole('button',{name:'定时任务',exact:true}).click();
  await expect(page).toHaveURL(/\/cron$/);
  await page.getByRole('button',{name:'新建计划',exact:true}).click();
  const catalog=await(await request.get('/api/schedules/catalog')).json();
  await page.getByRole('combobox',{name:'计划 Agent'}).selectOption(catalog.agents.find(a=>a.available).id);
  await expect(page.getByText('将执行 entrypoint.md')).toBeVisible();
  await page.getByRole('textbox',{name:'计划名称'}).fill('一次性财务检查');
  await page.getByLabel('执行日期',{exact:true}).fill('2099-01-02');
  await page.getByLabel('执行时间',{exact:true}).fill('09:30');
  await page.getByRole('combobox',{name:'执行时区'}).selectOption('Asia/Shanghai');
  await expect(page.locator('.cron-preview')).toContainText('2099/01/02 09:30');
  await page.getByRole('button',{name:'创建定时计划',exact:true}).click();
  const card=page.locator('.cron-plan').filter({has:page.getByRole('heading',{name:'一次性财务检查',exact:true})});
  await expect(card).toContainText('2099/01/02 09:30');
  await page.getByRole('button',{name:'暂停 一次性财务检查',exact:true}).click();
  await expect(card.locator('.cron-badge')).toHaveText('已暂停');
  await page.getByRole('button',{name:'恢复 一次性财务检查',exact:true}).click();
  await expect(card.locator('.cron-badge')).toHaveText('已启用');
  await page.reload();
  await expect(card).toBeVisible();
  const plans=await(await request.get('/api/schedules')).json();
  const plan=plans.find(p=>p.title==='一次性财务检查');
  expect((await request.post('/fixture/fire/'+plan.id)).ok()).toBeTruthy();
  await expect(card.locator('.cron-badge')).toHaveText('已触发',{timeout:20000});
  await card.getByRole('button',{name:'运行记录',exact:true}).click();
  await expect(page.locator('.cron-run strong')).toHaveText('已完成',{timeout:20000});
  await page.getByRole('button',{name:'查看报告',exact:true}).click();
  await expect(page.locator('.cron-report')).toContainText('checks_passed');
  await page.locator('.cron-report details summary').click();
  await expect(page.locator('.cron-report pre')).toContainText('"status": "completed"');
  await page.screenshot({path:'test-results/cron-report.png',fullPage:true});
  expect(errors).toEqual([]);
});

