  await page.screenshot({path:'test-results/cron-mobile-builder.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.getByRole('button',{name:'创建定时计划',exact:true}).click();
  const card=page.locator('.cron-plan').filter({has:page.getByRole('heading',{name:'每周分析',exact:true})});
