#!/usr/bin/env python3
"""Generate the build-time registry for first-party ``spa-module`` packages.

AIHO-33 D1 froze ``mcp.yaml`` as the only navigation/route declaration. This
script keeps the React build manifest-driven: every enabled-by-default package
with ``frontend.mount: spa-module`` is imported into the main SPA. Runtime
``enabled`` gating still happens through ``/api/mcp/packages`` and the package
page route; disabling a package never needs a rebuild.

Usage:
    python3 scripts/build_mcp_registry.py            # rewrite the generated file
    python3 scripts/build_mcp_registry.py --check    # fail when it is stale
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "frontend" / "src" / "mcp-registry.generated.js"
HEADER = "// Generated by scripts/build_mcp_registry.py; do not edit by hand.\n"

sys.path.insert(0, str(ROOT / "src"))

from agent_base.mcp_packages import discover  # noqa: E402


def rows() -> list[dict]:
    modules = []
    for package in discover(ROOT / "first_party").values():
        frontend = package.frontend
        if not frontend or frontend["mount"] != "spa-module":
            continue
        navigation = frontend["navigation"]
        modules.append({
            "id": package.id,
            "route": frontend["route"],
            "label": navigation["label"],
            "icon": navigation["icon"],
            "order": navigation["order"],
            "requires": list(frontend.get("requires", [])),
            "entry": os.path.relpath((package.root / frontend["entry"]).resolve(), TARGET.parent),
        })
    return sorted(modules, key=lambda item: (item["order"], item["id"]))


def render() -> str:
    lines = [HEADER, "export const mcpModules = ["]
    for item in rows():
        entry = str(item["entry"]).replace("\\", "/")
        lines.append("  {id: %s, route: %s, label: %s, icon: %s, order: %d, requires: %s," % (
            json.dumps(item["id"], ensure_ascii=False), json.dumps(item["route"], ensure_ascii=False),
            json.dumps(item["label"], ensure_ascii=False),
            json.dumps(item["icon"], ensure_ascii=False), item["order"],
            json.dumps(item["requires"], ensure_ascii=False)))
        lines.append("   load: () => import(%s)}," % json.dumps("./" + entry if not entry.startswith(".") else entry, ensure_ascii=False))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    value = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != value:
            print(f"{TARGET} 已过期，请运行 python3 scripts/build_mcp_registry.py")
            return 1
        print(f"{TARGET} 已是最新")
        return 0
    TARGET.write_text(value, encoding="utf-8")
    print(f"已写入 {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
